#!/usr/bin/env python3
"""Extract the Leads presets from AePresets.kt into a C++ header.

The presets are the source of truth for what the engine actually plays, so the click bench has to
run them rather than a hand-written approximation. The Kotlin list carries 32 values per preset; the
33rd (intensity) is added by the manager and is neutral, so it is appended here as 0.5.

Usage: python3 tools/aetherfx/extract_leads_presets.py > /tmp/leads_presets.h
"""
import re
import sys

SRC = "app/src/main/java/com/soundstage/mixer/instruments/AePresets.kt"


def main() -> int:
    text = open(SRC, encoding="utf-8").read()
    start = text.index("val leads: List<AePreset> = listOf(")
    end = text.index("val sax", start) if "val sax" in text[start:] else len(text)
    block = text[start:end]

    entries = re.findall(
        r'AePreset\(\s*"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*floatArrayOf\(([^)]*)\)',
        block,
        re.S,
    )

    out = ["// Generated by tools/aetherfx/extract_leads_presets.py - do not edit.", "#pragma once", ""]
    out.append("struct LeadPreset { const char* name; float v[33]; };")
    out.append("static const LeadPreset kLeadPresets[] = {")
    for name, category, values in entries:
        vals = [v.strip() for v in values.split(",") if v.strip()]
        floats = [float(v.rstrip("f")) for v in vals]
        if len(floats) != 32:
            print(f"// WARNING {name}: {len(floats)} values", file=sys.stderr)
        floats = (floats + [0.5] * 33)[:33]
        # Kotlin writes "0f"; C++ needs a decimal point.
        def lit(v: float) -> str:
            s = f"{v:.4g}"
            if "." not in s and "e" not in s and "inf" not in s:
                s += ".0"
            return s + "f"

        body = ", ".join(lit(v) for v in floats)
        out.append(f'  {{"{name}", {{{body}}}}},')
    out.append("};")
    out.append(f"static const int kLeadPresetCount = {len(entries)};")
    out.append("")
    print("\n".join(out))
    print(f"// {len(entries)} presets extracted", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
