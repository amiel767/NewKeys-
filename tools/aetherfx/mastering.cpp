// Mastering bench for the Æther Piano, off Android (aetherfx is header-only).
//   g++ -O2 -std=c++17 -I app/src/main/cpp mastering.cpp -o /tmp/ms
//
// Plays the real pack through the real engine with the real presets, and reports
// the numbers a mastering engineer looks at:
//
//   peak      : sample peak, must stay under 1.0 or the mixer limiter squashes it
//   rms       : programme level
//   crest     : peak/rms in dB -- too low means squashed, too high means spiky
//   decay     : energy after the key is released, the "dry" complaint
//   release   : time for the tail to fall 40 dB after noteOff
//   centroid  : spectral centre, the brightness axis
//
// The presets are read from a table generated by gen_presets.py, so this bench
// and AePianoUi.kt cannot drift apart.
#include <cstdio>
#include <cmath>
#include <cstring>
#include <cstdint>
#include <fstream>
#include <string>
#include <vector>
#include <algorithm>
#include <complex>
#include <array>

#include "aetherfx/fx_piano.h"

using namespace aetherfx;

static constexpr int SR = 44100;
static constexpr int BLK = 256;

struct Preset { std::string name; std::vector<float> v; };
static std::vector<Preset> gPresets;

static bool load_presets(const char* path) {
  std::ifstream f(path);
  if (!f) return false;
  std::string line;
  while (std::getline(f, line)) {
    if (line.empty() || line[0] == '#') continue;
    const size_t tab = line.find('|');
    if (tab == std::string::npos) continue;
    Preset p;
    p.name = line.substr(0, tab);
    std::string rest = line.substr(tab + 1);
    size_t pos = 0;
    while (pos < rest.size()) {
      size_t nxt = rest.find(',', pos);
      if (nxt == std::string::npos) nxt = rest.size();
      p.v.push_back(std::stof(rest.substr(pos, nxt - pos)));
      pos = nxt + 1;
    }
    gPresets.push_back(p);
  }
  return !gPresets.empty();
}

static std::vector<uint8_t> read_file(const char* path) {
  std::ifstream f(path, std::ios::binary);
  return std::vector<uint8_t>((std::istreambuf_iterator<char>(f)),
                              std::istreambuf_iterator<char>());
}

// Iterative radix-2 FFT, so the centroid costs n log n instead of n^2.
static void fft(std::vector<std::complex<double>>& a) {
  const size_t n = a.size();
  for (size_t i = 1, j = 0; i < n; ++i) {
    size_t bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) std::swap(a[i], a[j]);
  }
  for (size_t len = 2; len <= n; len <<= 1) {
    const double ang = -2 * M_PI / len;
    const std::complex<double> wl(std::cos(ang), std::sin(ang));
    for (size_t i = 0; i < n; i += len) {
      std::complex<double> w(1, 0);
      for (size_t k = 0; k < len / 2; ++k) {
        const std::complex<double> u = a[i + k], v = a[i + k + len / 2] * w;
        a[i + k] = u + v;
        a[i + k + len / 2] = u - v;
        w *= wl;
      }
    }
  }
}

struct Stats { double peak = 0, rms = 0, centroid = 0, hf = 0, lk = 0;
               double band[5] = {0, 0, 0, 0, 0}; double noise = 0; };

// The bank carries nothing above ~6 kHz, so any output energy up there is codec
// noise.  Measured against the 0-3 kHz band, it is the one honest quality figure:
// lower is better, and it does not depend on how loud the preset is.
static double noise_floor(const std::vector<float>& mono) {
  size_t n = 1;
  while (n * 2 <= mono.size() && n < (1u << 16)) n <<= 1;
  std::vector<std::complex<double>> buf(n);
  for (size_t i = 0; i < n; ++i)
    buf[i] = mono[i] * (0.5 - 0.5 * std::cos(2 * M_PI * i / (n - 1)));
  fft(buf);
  double sig = 0, noise = 0;
  for (size_t k = 1; k < n / 2; ++k) {
    const double f = k * static_cast<double>(SR) / n;
    const double p = std::norm(buf[k]);
    if (f < 3000) sig += p;
    else if (f >= 6000 && f < 11000) noise += p;
  }
  return 10 * std::log10((noise + 1e-30) / (sig + 1e-30));
}

// K-weighted loudness (ITU-R BS.1770 pre-filter).  Plain RMS is dominated by the
// bass of a piano and rates two patches that sound equally loud 3 dB apart, so
// the level balance has to be judged on this instead.
static double k_weight(const std::vector<float>& x) {
  const double f0 = 1681.974450955533, Q0 = 0.7071752369554196, G0 = 3.999843853973347;
  const double f1 = 38.13547087602444, Q1 = 0.5003270373238773;
  auto coeffs = [&](double f, double Q, double g) {
    const double K = std::tan(M_PI * f / SR);
    const double Vh = std::pow(10.0, g / 20.0), Vb = std::pow(Vh, 0.4996667741545416);
    const double a0 = 1 + K / Q + K * K;
    return std::array<double, 5>{
        (Vh + Vb * K / Q + K * K) / a0, 2 * (K * K - Vh) / a0,
        (Vh - Vb * K / Q + K * K) / a0, 2 * (K * K - 1) / a0, (1 - K / Q + K * K) / a0};
  };
  const auto s1 = coeffs(f0, Q0, G0);
  const auto s2 = coeffs(f1, Q1, 0.0);
  double z1[2] = {0, 0}, z2[2] = {0, 0};
  double acc = 0;
  for (float xf : x) {
    const double in = xf;
    const double y1 = s1[0] * in + z1[0];
    z1[0] = s1[1] * in - s1[3] * y1 + z1[1];
    z1[1] = s1[2] * in - s1[4] * y1;
    const double y2 = s2[0] * y1 + z2[0];
    z2[0] = s2[1] * y1 - s2[3] * y2 + z2[1];
    z2[1] = s2[2] * y1 - s2[4] * y2;
    acc += y2 * y2;
  }
  return 10 * std::log10(acc / std::max<size_t>(x.size(), 1) + 1e-30);
}

static Stats analyse(const std::vector<float>& mono) {
  Stats s;
  if (mono.empty()) return s;
  for (float x : mono) s.peak = std::max(s.peak, static_cast<double>(std::fabs(x)));
  double acc = 0;
  for (float x : mono) acc += static_cast<double>(x) * x;
  s.rms = std::sqrt(acc / mono.size());

  size_t n = 1;
  while (n * 2 <= mono.size() && n < (1u << 16)) n <<= 1;
  std::vector<std::complex<double>> buf(n);
  for (size_t i = 0; i < n; ++i)
    buf[i] = mono[i] * (0.5 - 0.5 * std::cos(2 * M_PI * i / (n - 1)));
  fft(buf);
  double num = 0, den = 0, hi = 0;
  const double edges[6] = {0, 300, 800, 2000, 4000, 8000};
  double bandE[5] = {0, 0, 0, 0, 0};
  for (size_t k = 1; k < n / 2; ++k) {
    const double p = std::norm(buf[k]);
    const double f = k * static_cast<double>(SR) / n;
    num += f * p;
    den += p;
    if (f >= 4000) hi += p;
    for (int b = 0; b < 5; ++b)
      if (f >= edges[b] && f < edges[b + 1]) bandE[b] += p;
  }
  for (int b = 0; b < 5; ++b)
    s.band[b] = den > 0 ? 10 * std::log10((bandE[b] + 1e-30) / den) : -99;
  s.centroid = den > 0 ? num / den : 0;
  s.hf = den > 0 ? 10 * std::log10((hi + 1e-30) / den) : -99;
  s.lk = k_weight(mono);
  s.noise = noise_floor(mono);
  return s;
}

// Renders one note.  Returns mono, plus the tail level 0.5 s after noteOff
// relative to the level just before it, and the time to fall 40 dB.
static void render(PianoEngine& eng, const std::vector<float>& v, int note, int vel,
                   double hold, std::vector<float>& out, double& tailDb, double& rel40) {
  for (int i = 0; i < PianoEngine::kParams; ++i)
    eng.setNorm(i, i < static_cast<int>(v.size()) ? v[i] : 0.5f);
  eng.reset();
  out.clear();
  eng.noteOn(note, vel);
  const int blocks = static_cast<int>((hold + 3.0) * SR / BLK);
  const int relBlock = static_cast<int>(hold * SR / BLK);
  std::vector<float> buf(BLK * 2);
  std::vector<double> win;                       // 20 ms RMS windows after release
  double before = 0;
  int nBefore = 0;
  double acc = 0;
  int nAcc = 0;
  for (int b = 0; b < blocks; ++b) {
    if (b == relBlock) eng.noteOff(note);
    std::fill(buf.begin(), buf.end(), 0.f);
    eng.process(buf.data(), BLK);
    for (int j = 0; j < BLK; ++j) {
      const double m = 0.5 * (buf[2 * j] + buf[2 * j + 1]);
      out.push_back(static_cast<float>(m));
      if (b < relBlock) { before += m * m; nBefore++; }
      acc += m * m;
      if (++nAcc >= SR / 50) { win.push_back(acc / nAcc); acc = 0; nAcc = 0; }
    }
  }
  const double pre = before / std::max(nBefore, 1);
  const size_t relWin = static_cast<size_t>(relBlock / (SR / 50));
  tailDb = (relWin + 25 < win.size() && pre > 0)
               ? 10 * std::log10((win[relWin + 25] + 1e-20) / pre) : -99;
  rel40 = 0;
  for (size_t i = relWin; i < win.size(); ++i) {
    if (pre > 0 && 10 * std::log10((win[i] + 1e-20) / pre) < -40) {
      rel40 = (i - relWin) / 50.0;
      break;
    }
  }
}

int main(int argc, char** argv) {
  if (argc < 3) {
    std::fprintf(stderr, "usage: %s <piano.bin> <presets.txt> [phrase|single]\n", argv[0]);
    return 2;
  }
  if (!load_presets(argv[2])) { std::fprintf(stderr, "no presets\n"); return 2; }
  auto bin = read_file(argv[1]);
  if (bin.empty()) { std::fprintf(stderr, "no pack\n"); return 2; }
  const bool phrase = (argc > 3 && std::string(argv[3]) == "phrase");

  PianoEngine eng;
  eng.prepare(SR, BLK);
  if (!eng.loadSampleBank(bin.data(), bin.size())) {
    std::fprintf(stderr, "pack refused by the engine\n");
    return 2;
  }
  std::printf("pack ok\n\n");

  // A short musical phrase, so the measurement is not one note's luck: a bass
  // note held under an arpeggio, which is how the instrument is actually played.
  const int chord[] = {48, 55, 60, 64, 67, 72};
  const int single[] = {60};
  // Ten notes at full velocity: the worst case the strip will ever see.
  const int stress[] = {36, 43, 48, 52, 55, 60, 64, 67, 72, 76};
  const bool retune = (argc > 3 && std::string(argv[3]) == "retune");
  const bool stressMode = (argc > 3 && std::string(argv[3]) == "stress");
  // Does velocity change the TIMBRE, or only the level?  If only the level, the
  // soft layers are redundant and can be dropped.  Each take is normalised to the
  // same RMS first, so what is left is the timbre alone.
  const bool velMode = (argc > 3 && std::string(argv[3]) == "vel");
  // Target programme RMS.  Resolved below as the QUIETEST preset at its designed
  // LEVEL: equal loudness must not be bought with a boost, because LEVEL also
  // feeds the drive stage and the mixer strip already owns absolute gain.  So the
  // loud presets come down instead of the quiet ones going up.
  double targetLk = 0.0;

  if (!retune)
    std::printf("%-14s %6s %6s %8s %8s\n",
                "preset", "peak", "rms", "centHz", "noise");

  // Velocity timbre check: hold LEVEL and SPACE fixed so the comparison is purely
  // about which sample the reader chose.
  if (velMode) {
    PianoSampleReader probe;                       // same pack, for layer lookup
    probe.load(bin.data(), bin.size());
    std::vector<float> flat = gPresets[1].v;      // Studio: the neutral preset
    flat[7] = 0.8f;                                // LEVEL
    flat[5] = 0.4f;                                // SPACE, so lvl is constant
    std::printf("each take normalised to equal RMS, so what differs is the timbre\n\n");
    std::printf("%-4s %5s | %6s %6s %6s %6s %6s | %7s\n",
                "vel", "layer", "0-300", "300-8", "0.8-2k", "2-4k", "4-8k", "centHz");
    for (int vel : {8, 24, 40, 56, 72, 88, 104, 120}) {
      std::vector<float> mono;
      double t = 0, rr = 0;
      render(eng, flat, 60, vel, 0.5, mono, t, rr);
      Stats s = analyse(mono);
      // Normalise to a common RMS so the level does not mask the timbre.
      for (float& x : mono) x = static_cast<float>(x / (s.rms + 1e-12) * 0.05);
      Stats n = analyse(mono);
      const double crest = 20 * std::log10(n.peak / (n.rms + 1e-12) + 1e-12);
      const auto* g = probe.pick(60, vel);
      std::printf("%-4d %5d | %6.1f %6.1f %6.1f %6.1f %6.1f | %7.0f\n", vel,
                  g ? g->layer : -1, n.band[0], n.band[1], n.band[2], n.band[3],
                  n.band[4], n.centroid);
    }
    return 0;
  }

  // LEVEL is applied as a plain output multiply, after every other stage, so the
  // value that hits the target loudness is exact in one step.  A bisection here
  // would only add quantisation error.
  auto solveLevel = [&](double level, double lkNow, double target) {
    return std::min(1.0, std::max(0.0, level * std::pow(10.0, (target - lkNow) / 20.0)));
  };

  // First pass: measure every preset as designed.
  std::vector<Stats> base(gPresets.size());
  if (retune) {
    std::vector<double> lks;
    for (size_t i = 0; i < gPresets.size(); ++i) {
      std::vector<float> all;
      double a = 0, b = 0;
      for (int k = 0; k < 6; ++k) {
        std::vector<float> one;
        render(eng, gPresets[i].v, chord[k], 70 + k * 8, 0.6, one, a, b);
        all.insert(all.end(), one.begin(), one.end());
      }
      base[i] = analyse(all);
      lks.push_back(base[i].lk);
    }
    // Median, not minimum: equal loudness should not cost any preset a big
    // attenuation.  The quietest preset defines the floor, the median is the
    // level the majority already sits at.
    std::sort(lks.begin(), lks.end());
    targetLk = lks[lks.size() / 2];
    std::printf("target K-weighted loudness %.1f dB (median; spread was %.1f dB)\n\n",
                targetLk, lks.back() - lks.front());
  }

  for (size_t pi = 0; pi < gPresets.size(); ++pi) {
    const auto& p = gPresets[pi];
    std::vector<float> all;
    double tail = 0, rel40 = 0;
    if (stressMode) {
      std::vector<float> one;
      double t = 0, r = 0;
      for (int i = 0; i < 10; ++i) {
        render(eng, p.v, stress[i], 127, 2.0, one, t, r);
        tail = std::max(tail, t); rel40 = std::max(rel40, r);
        all.insert(all.end(), one.begin(), one.end());
      }
    } else if (phrase || retune) {
      std::vector<float> one;
      for (int i = 0; i < 6; ++i) {
        double t = 0, r = 0;
        render(eng, p.v, chord[i], 70 + i * 8, 0.6, one, t, r);
        tail = std::max(tail, t);
        rel40 = std::max(rel40, r);
        all.insert(all.end(), one.begin(), one.end());
      }
    } else {
      render(eng, p.v, single[0], 100, 1.5, all, tail, rel40);
    }
    Stats s = analyse(all);
    const double crest = 20 * std::log10(s.peak / (s.rms + 1e-12) + 1e-12);

    if (!retune) {
      std::printf("%-14s %6.3f %6.3f %8.0f %8.1f%s\n",
                  p.name.c_str(), s.peak, s.rms, s.centroid, s.noise,
                  s.peak > 0.999 ? "  CLIP" : "");
      continue;
    }

    // Equal loudness: every preset lands on the same programme RMS, so no model
    // is louder than another for a reason nobody chose.
    std::vector<float> v = p.v;
    v[7] = static_cast<float>(solveLevel(p.v[7], base[pi].lk, targetLk));
    std::vector<float> after;
    double t2 = 0, r2 = 0;
    for (int i = 0; i < 6; ++i) {
      std::vector<float> one;
      render(eng, v, chord[i], 70 + i * 8, 0.6, one, t2, r2);
      after.insert(after.end(), one.begin(), one.end());
    }
    Stats s2 = analyse(after);
    std::printf("%s|", p.name.c_str());
    for (size_t i = 0; i < v.size(); ++i)
      std::printf("%s%.4f", i ? "," : "", v[i]);
    std::printf("   // level %.3f -> %.3f  rms %.4f -> %.4f  peak %.3f -> %.3f  hf %.1f -> %.1f\n",
                p.v[7], v[7], s.rms, s2.rms, s.peak, s2.peak, s.hf, s2.hf);
  }
  return 0;
}
