#!/usr/bin/env python3
"""Extracts the sax presets from AePresets.kt into a C++ header.

The presets are the single source of truth in Kotlin; duplicating them here by hand
would drift. Re-run after any preset edit.
"""
import re, sys, pathlib

SRC = pathlib.Path(__file__).resolve().parents[2] / "app/src/main/java/com/soundstage/mixer/instruments/AePresets.kt"
OUT = pathlib.Path(__file__).resolve().parent / "presets_sax.h"

def main():
    s = SRC.read_text(encoding="utf-8")
    i = s.find("val sax")
    if i < 0:
        sys.exit("no `val sax` in AePresets.kt")
    block = s[i:s.find("\n    )", i)]
    rows = re.findall(r'AePreset\("([^"]+)",\s*"([^"]+)",\s*floatArrayOf\(([^)]*)\)\)', block)
    if not rows:
        sys.exit("no preset parsed")
    lines = ["// GENERATED by tools/saxdemo/gen_presets.py -- do not edit.",
             "#pragma once", "", "struct SaxPreset { const char* name; const char* category; float v[23]; };",
             "", "static const SaxPreset SAX_PRESETS[] = {"]
    for name, cat, vals in rows:
        v = [x.strip().rstrip("f") for x in vals.split(",")]
        if len(v) != 23:
            sys.exit(f"{name}: {len(v)} values, expected 23")
        joined = ", ".join(v)
        lines.append(f'  {{"{name}", "{cat}", {{{joined}}}}},')
    lines += ["};", f'static const int SAX_PRESET_COUNT = {len(rows)};', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} presets -> {OUT.name}")

if __name__ == "__main__":
    main()
